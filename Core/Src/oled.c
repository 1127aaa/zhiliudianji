/* SSD1306 I2C 地址（7 位 0x3C 左移一位） */
#define OLED_I2C_ADDR    0x78
#define OLED_CMD_BYTE    0x00
#define OLED_DATA_BYTE   0x40
#define OLED_WIDTH       128
#define OLED_TIMEOUT     100

